CREATE DATABASE WasteCollectionDB;

USE WasteCollectionDB;

CREATE TABLE Customers (
    CustomerID INT AUTO_INCREMENT PRIMARY KEY,
    CustomerName VARCHAR(100) NOT NULL,
    Phone VARCHAR(15) NOT NULL,
    Email VARCHAR(100),
    Address VARCHAR(200) NOT NULL,
    Area VARCHAR(50) NOT NULL,
    WasteType VARCHAR(30) NOT NULL
);

CREATE TABLE Vehicles (
    VehicleID INT AUTO_INCREMENT PRIMARY KEY,
    VehicleNumber VARCHAR(20) UNIQUE NOT NULL,
    VehicleType VARCHAR(30) NOT NULL,
    CapacityKg INT NOT NULL,
    Status VARCHAR(20) NOT NULL
);

CREATE TABLE Drivers (
    DriverID INT AUTO_INCREMENT PRIMARY KEY,
    DriverName VARCHAR(100) NOT NULL,
    Phone VARCHAR(15) NOT NULL,
    LicenseNumber VARCHAR(30) UNIQUE NOT NULL,
    VehicleID INT,
    FOREIGN KEY (VehicleID) REFERENCES Vehicles(VehicleID)
);

CREATE TABLE CollectionSchedule (
    ScheduleID INT AUTO_INCREMENT PRIMARY KEY,
    CustomerID INT NOT NULL,
    DriverID INT NOT NULL,
    CollectionDate DATE NOT NULL,
    CollectionTime TIME NOT NULL,
    Status VARCHAR(20) NOT NULL,
    FOREIGN KEY (CustomerID) REFERENCES Customers(CustomerID),
    FOREIGN KEY (DriverID) REFERENCES Drivers(DriverID)
);

CREATE TABLE WasteCollection (
    CollectionID INT AUTO_INCREMENT PRIMARY KEY,
    ScheduleID INT NOT NULL,
    WasteWeightKg DECIMAL(6,2) NOT NULL,
    WasteType VARCHAR(30) NOT NULL,
    CollectionStatus VARCHAR(20) NOT NULL,
    FOREIGN KEY (ScheduleID) REFERENCES CollectionSchedule(ScheduleID)
);

CREATE TABLE Payments (
    PaymentID INT AUTO_INCREMENT PRIMARY KEY,
    CustomerID INT NOT NULL,
    Amount DECIMAL(8,2) NOT NULL,
    PaymentDate DATE NOT NULL,
    PaymentMode VARCHAR(20) NOT NULL,
    PaymentStatus VARCHAR(20) NOT NULL,
    FOREIGN KEY (CustomerID) REFERENCES Customers(CustomerID)
);

